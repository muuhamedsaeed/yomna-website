-- Client logos for the "Trusted By" tape on the home page.
-- Run once in the Supabase SQL Editor (after 01-03). Logo files are uploaded
-- from the admin Clients page into the existing public `portfolio-assets` bucket.

create table if not exists public.client_logos (
  id bigint generated by default as identity primary key,
  name text not null default '',
  logo_url text not null,
  sort_order integer not null unique
);

alter table public.client_logos enable row level security;

drop policy if exists "Public can read client logos" on public.client_logos;
create policy "Public can read client logos" on public.client_logos
  for select to anon, authenticated using (true);

drop policy if exists "Portfolio admin manages client logos" on public.client_logos;
create policy "Portfolio admin manages client logos" on public.client_logos
  for all to authenticated
  using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

grant select on public.client_logos to anon, authenticated;
grant insert, update, delete on public.client_logos to authenticated;
grant usage, select on all sequences in schema public to authenticated;
