-- Project types for the Work page filters and Projects admin section.
-- Run once in the Supabase SQL Editor (after 01-03).

create table if not exists public.project_types (
  id bigint generated by default as identity primary key,
  label text not null,
  sort_order integer not null unique
);

alter table public.project_types enable row level security;

drop policy if exists "Public can read project types" on public.project_types;
create policy "Public can read project types" on public.project_types
  for select to anon, authenticated using (true);

drop policy if exists "Portfolio admin manages project types" on public.project_types;
create policy "Portfolio admin manages project types" on public.project_types
  for all to authenticated
  using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

grant select on public.project_types to anon, authenticated;
grant insert, update, delete on public.project_types to authenticated;
grant usage, select on all sequences in schema public to authenticated;

insert into public.project_types (label, sort_order) values
  ('Social Media', 1),
  ('Campaigns', 2),
  ('Reels', 3),
  ('Promos', 4),
  ('Event Visuals', 5),
  ('Other', 6)
on conflict (sort_order) do nothing;
